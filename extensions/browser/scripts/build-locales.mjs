/** Turns `$1`-style substitutions into named placeholders. */
function toEntry(message, description) {
  /** @type {{message: string, description?: string, placeholders?: Record<string, {content: string}>}} */
  const entry = { message };
  const numbers = [...new Set([...message.matchAll(/\$(\d)/g)].map((m) => m[1]))];
  if (numbers.length > 0) {
    entry.message = message.replace(/\$(\d)/g, (_m, n) => `$ARG${n}$`);
    entry.placeholders = {};
    for (const n of numbers) entry.placeholders[`arg${n}`] = { content: `$${n}` };
  }
  if (description) entry.description = description;
  return entry;
}

function writeLocale(lang, translations) {
  const dir = path.join(ROOT, '_locales', lang);
  mkdirSync(dir, { recursive: true });
  const out = {};
  let missing = 0;
  for (const [key, message] of Object.entries(en)) {
    const translated = translations?.[key];
    if (translations && translated === undefined) missing += 1;
    out[key] = translated !== undefined
      ? toEntry(translated)
      : toEntry(message, translations ? '[fallback: needs translation]' : undefined);
  }
  for (const key of Object.keys(translations ?? {})) {
    if (!(key in en)) throw new Error(`${lang}: "${key}" is not an English key`);
  }
  writeFileSync(path.join(dir, 'messages.json'), `${JSON.stringify(out, null, 2)}\n`);
  console.log(`wrote _locales/${lang}/messages.json (${Object.keys(out).length} keys, ${missing} untranslated)`);
}

writeLocale('en', null);
writeLocale('hi', hi);
